def clarify_for(slot: str) -> str:
    return CLARIFY.get(slot, "Уточните, пожалуйста, детали вашей задачи.")


def partial(covered_answer: str, missing_aspect: str) -> str:
    covered = (covered_answer or "").strip()
    missing = missing_aspect or "этого"
    if covered:
        return PARTIAL_TMPL.format(covered_answer=covered, missing_aspect=missing)
    return NOT_IN_KB


def with_cta(answer: str) -> str:
    a = (answer or "").rstrip()
    if not a:
        return CTA
    if "?" in a[-40:]:
        return a
    return f"{a} {CTA}"
